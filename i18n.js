        if (str.includes('kannada') || str.includes('ಕನ್ನಡ')) return 'kn';
        if (str.includes('malayalam') || str.includes('മലയാളം')) return 'ml';
        if (str.includes('marathi') || str.includes('मराठी')) return 'mr';
        if (str.includes('gujarati') || str.includes('ગુજરાતી')) return 'gu';
        if (str.includes('punjabi') || str.includes('ਪੰਜਾਬੀ')) return 'pa';
        if (str.includes('urdu') || str.includes('اردو')) return 'ur';
        if (str.includes('spanish') || str.includes('español')) return 'es';
        if (str.includes('french') || str.includes('français')) return 'fr';
        if (str.includes('german') || str.includes('deutsch')) return 'de';
        if (str.includes('chinese') || str.includes('中文')) return 'zh';
